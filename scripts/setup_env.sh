#!/usr/bin/env bash
# Generates .env from environment variables (for cloud sessions).
# Run once after starting a new session.
set -euo pipefail

ENV_FILE="$(dirname "$0")/../.env"

cat > "$ENV_FILE" <<EOF
APP_HOST=127.0.0.1
APP_PORT=8765
APP_ENV=development
APP_SECRET_KEY=
DATABASE_URL=sqlite+aiosqlite:///./data/app.db

CAPTCHA_PROVIDER=${CAPTCHA_PROVIDER:-capsolver}
CAPSOLVER_API_KEY=${capsolver_api:-${CAPSOLVER_API_KEY:-}}
ANTICAPTCHA_API_KEY=${ANTICAPTCHA_API_KEY:-}
TWOCAPTCHA_API_KEY=${TWOCAPTCHA_API_KEY:-}
EZCAPTCHA_API_KEY=${EZCAPTCHA_API_KEY:-}
CAPTCHA_SOLVE_ENABLED=${capsolver_enabled:-${CAPTCHA_SOLVE_ENABLED:-false}}

PROXY_URL=${proxy_url:-${PROXY_URL:-}}

SMS_PROVIDER_NAME=${SMS_PROVIDER_NAME:-generic}
SMS_PROVIDER_API_KEY=${SMS_PROVIDER_API_KEY:-}
SMS_PROVIDER_BASE_URL=${SMS_PROVIDER_BASE_URL:-}

MSGRAPH_CLIENT_ID=${MSGRAPH_CLIENT_ID:-}
MSGRAPH_TENANT_ID=${MSGRAPH_TENANT_ID:-}
MSGRAPH_REDIRECT_URI=${MSGRAPH_REDIRECT_URI:-http://localhost:8765/api/v1/auth/msgraph/callback}

BROWSER_HEADLESS=${BROWSER_HEADLESS:-true}
BROWSER_TIMEOUT_MS=${BROWSER_TIMEOUT_MS:-30000}

LOG_LEVEL=${LOG_LEVEL:-INFO}
LOG_FILE=logs/app.log

MAX_WORKER_COUNT=${MAX_WORKER_COUNT:-10}
MAX_QUEUE_SIZE=${MAX_QUEUE_SIZE:-1000}
JOB_TIMEOUT_SECONDS=${JOB_TIMEOUT_SECONDS:-300}
MAX_RETRIES=${MAX_RETRIES:-3}
IMPORT_MAX_ROWS=${IMPORT_MAX_ROWS:-10000}
BACKUP_RETENTION_DAYS=${BACKUP_RETENTION_DAYS:-30}
EOF

echo ".env generated at $ENV_FILE"
